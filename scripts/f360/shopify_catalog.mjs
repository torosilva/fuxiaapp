// Shopify México catalog → SQL that refreshes f360.shopify_variants (READ-ONLY against Shopify and the Woo store).
// Reads the app credentials from ~/.fuxia-shopify.client_id and ~/.fuxia-shopify.secret (never printed), asks Shopify for a
// 24 h token (client_credentials), lists every variant, and adds hints from the old Woo product with the same slug
// (fuxiaballerinas.com/co, which still serves the shared catalog). Writes ONLY a SQL file; applying it is a separate step
// (staging runner or a production pase). Docs: docs/fuxia360/omnichannel/SHOPIFY_MX.md §3.
// Run: node scripts/f360/shopify_catalog.mjs <out.sql> [target_key=shopify_mx]
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';

const SHOP = 'z9fdqc-0z.myshopify.com';
const API = '2026-10';
const WOO_STORE_API = 'https://fuxiaballerinas.com/co/wp-json/wc/store/v1/products';
const [out, targetKey = 'shopify_mx'] = process.argv.slice(2);
if (!out) throw new Error('uso: shopify_catalog.mjs <out.sql> [target_key]');
if (!/^[a-z0-9_]+$/.test(targetKey)) throw new Error('target_key inválido');

const read = (f) => readFileSync(`${homedir()}/${f}`, 'utf8').trim();
const tokenRes = await fetch(`https://${SHOP}/admin/oauth/access_token`, {
  method: 'POST', headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
  body: new URLSearchParams({ grant_type: 'client_credentials', client_id: read('.fuxia-shopify.client_id'), client_secret: read('.fuxia-shopify.secret') }),
});
if (!tokenRes.ok) throw new Error(`Shopify token → ${tokenRes.status}`);
const { access_token: token } = await tokenRes.json();

async function gql(query, variables) {
  const r = await fetch(`https://${SHOP}/admin/api/${API}/graphql.json`, {
    method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Shopify-Access-Token': token }, body: JSON.stringify({ query, variables }),
  });
  const j = await r.json();
  if (!r.ok || j.errors) throw new Error(`Shopify GraphQL → ${r.status} ${JSON.stringify(j.errors ?? j).slice(0, 300)}`);
  return j.data;
}

const idOf = (gid) => Number(String(gid).split('/').pop());
const variants = [];
for (let after = null; ;) {
  const d = await gql(`query($after: String) { productVariants(first: 250, after: $after) {
      pageInfo { hasNextPage endCursor }
      nodes { id sku selectedOptions { name value } inventoryItem { id } product { id handle title } } } }`, { after });
  for (const v of d.productVariants.nodes) {
    const opt = (n) => v.selectedOptions.find((o) => o.name.toLowerCase() === n)?.value ?? null;
    variants.push({ sid: idOf(v.id), pid: idOf(v.product.id), item: v.inventoryItem ? idOf(v.inventoryItem.id) : null, handle: v.product.handle,
      title: v.product.title, color: opt('color'), size: opt('talla') ?? opt('size') ?? opt('medida'), sku: v.sku || null });
  }
  if (!d.productVariants.pageInfo.hasNextPage) break;
  after = d.productVariants.pageInfo.endCursor;
}

// Hints from the old Woo product with the same slug. A variation counts only when it carries its OWN colour and is the only
// one with that colour + size (variations without a colour attribute would match every colour).
const norm = (s) => String(s ?? '').normalize('NFKD').replace(/[̀-ͯ]/g, '').trim().toLowerCase();
const woo = new Map();
for (const handle of new Set(variants.map((v) => v.handle))) {
  const r = await fetch(`${WOO_STORE_API}?slug=${encodeURIComponent(handle)}`, { headers: { 'User-Agent': 'Fuxia360-catalog/1.0' } });
  const list = r.ok ? await r.json() : [];
  if (Array.isArray(list) && list[0]) woo.set(handle, list[0]);
}
for (const v of variants) {
  const p = woo.get(v.handle);
  v.woo_pid = p?.id ?? null;
  const hits = (p?.variations ?? []).filter((x) => {
    const a = Object.fromEntries(x.attributes.map((t) => [norm(t.name), norm(t.value)]));
    return a.color && a.color.replace(/-/g, ' ') === norm(v.color) && (a.medida ?? a.talla) === norm(v.size);
  });
  v.woo_vid = hits.length === 1 ? hits[0].id : null;
}

const q = (x) => (x === null || x === undefined ? 'NULL' : typeof x === 'number' ? `${x}::bigint` : `'${String(x).replace(/'/g, "''")}'::text`);
const rows = variants.map((v) => `(${[v.sid, v.pid, v.item, v.handle, v.title, v.color, v.size, v.sku, v.woo_pid, v.woo_vid].map(q).join(', ')})`);
writeFileSync(out, `-- GENERATED by scripts/f360/shopify_catalog.mjs (${new Date().toISOString()}) — ${variants.length} variantes de ${SHOP}.
CREATE TEMP TABLE shopify_catalog_in ON COMMIT DROP AS SELECT * FROM (VALUES
${rows.join(',\n')}
) v(shopify_variant_id, shopify_product_id, inventory_item_id, handle, product_title, color, size, sku, woo_product_id, woo_variation_id);
INSERT INTO f360.shopify_products (target_id, shopify_product_id)
SELECT DISTINCT (SELECT id FROM f360.sales_targets WHERE key = '${targetKey}' AND kind = 'shopify'), shopify_product_id::bigint FROM shopify_catalog_in
ON CONFLICT DO NOTHING;
INSERT INTO f360.shopify_variants (target_id, shopify_variant_id, shopify_product_id, inventory_item_id, handle, product_title, color, size, sku, woo_product_id, woo_variation_id, seen_at)
SELECT (SELECT id FROM f360.sales_targets WHERE key = '${targetKey}' AND kind = 'shopify'), v.*, now() FROM shopify_catalog_in v
ON CONFLICT (target_id, shopify_variant_id) DO UPDATE SET shopify_product_id = EXCLUDED.shopify_product_id, inventory_item_id = EXCLUDED.inventory_item_id,
  handle = EXCLUDED.handle, product_title = EXCLUDED.product_title, color = EXCLUDED.color, size = EXCLUDED.size, sku = EXCLUDED.sku,
  woo_product_id = EXCLUDED.woo_product_id, woo_variation_id = EXCLUDED.woo_variation_id, seen_at = now();
`);
console.log(`${variants.length} variantes · ${woo.size} productos con su producto Woo · ${variants.filter((v) => v.woo_vid).length} con variación Woo única → ${out}`);
